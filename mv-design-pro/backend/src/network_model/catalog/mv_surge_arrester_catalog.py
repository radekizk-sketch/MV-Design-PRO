def get_all_surge_arrester_types() -> list[dict[str, Any]]:
    return list(SURGE_ARRESTER_TYPES)


def get_surge_arrester_catalog_statistics() -> dict[str, Any]:
    records = get_all_surge_arrester_types()
    params = [record["params"] for record in records]
    return {
        "liczba_ogranicznikow_ogolem": len(records),
        "napiecia_um_kv": sorted({float(item["u_m_kv"]) for item in params}),
        "producenci": sorted({str(item["manufacturer"]) for item in params}),
        "klasy_energetyczne": sorted({int(item["energy_class"]) for item in params}),
        "statusy_weryfikacji": sorted(Counter(str(item["verification_status"]) for item in params)),
        "statusy_katalogowe": sorted(Counter(str(item["catalog_status"]) for item in params)),
        "contract_version": CATALOG_CONTRACT_VERSION,
    }
