SOURCE_REFERENCE = "PN-EN 60099-4 / IEC 60099-4 / referencyjny typoszereg ogranicznikow SN"


def _record(
    *,
    item_id: str,
    name: str,
    manufacturer: str,
    model: str,
    u_m_kv: float,
    mcov_kv: float,
    u_rated_kv: float,
    u_residual_at_10ka_kv: float,
    tov_10s_kv: float,
    energy_class: int,
    energy_absorption_kj_per_kv: float,
    bil_protected_kv: float,
    application: str,
    neutral_system: str,
) -> dict[str, Any]:
    return {
        "id": item_id,
        "name": name,
        "params": {
            "u_m_kv": u_m_kv,
            "mcov_kv": mcov_kv,
            "u_rated_kv": u_rated_kv,
            "u_residual_at_10ka_kv": u_residual_at_10ka_kv,
            "tov_10s_kv": tov_10s_kv,
            "energy_class": energy_class,
            "energy_absorption_kj_per_kv": energy_absorption_kj_per_kv,
            "bil_protected_kv": bil_protected_kv,
            "application": application,
            "neutral_system": neutral_system,
            "manufacturer": manufacturer,
            "model": model,
            "standard": "PN-EN 60099-4",
            "verification_status": CatalogVerificationStatus.REFERENCYJNY.value,
            "catalog_status": CatalogStatus.REFERENCYJNY_V1.value,
            "source_reference": SOURCE_REFERENCE,
            "contract_version": CATALOG_CONTRACT_VERSION,
            "verification_note": (
                "Rekord referencyjny do doboru wstepnego. Dobor wykonawczy wymaga "
                "karty katalogowej producenta i weryfikacji TOV dla ukladu sieci."
            ),
        },
    }


