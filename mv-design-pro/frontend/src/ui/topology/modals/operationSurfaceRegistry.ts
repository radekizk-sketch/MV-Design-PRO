import type { CanonicalOpName } from '../../../types/domainOps';
import type {
  WorkspaceOpenMode,
  WorkspaceScreenCode,
  WorkspaceSurfaceSaveMode,
  WorkspaceSurfaceSizeClass,
} from '../../workspace/types';

export interface OperationSurfaceEntry {
  canonicalOp: CanonicalOpName;
  componentName: string;
  labelPl: string;
  implemented: boolean;
  screenCode: WorkspaceScreenCode;
  sizeClass: WorkspaceSurfaceSizeClass;
  saveMode: WorkspaceSurfaceSaveMode;
  openMode: WorkspaceOpenMode;
  supportsMiniSld: boolean;
  defaultTab: string | null;
}

function entry(
  canonicalOp: CanonicalOpName,
  componentName: string,
  labelPl: string,
  screenCode: WorkspaceScreenCode,
  sizeClass: WorkspaceSurfaceSizeClass,
  saveMode: WorkspaceSurfaceSaveMode,
  openMode: WorkspaceOpenMode,
  supportsMiniSld: boolean,
  defaultTab: string | null,
): OperationSurfaceEntry {
  return {
    canonicalOp,
    componentName,
    labelPl,
    implemented: true,
    screenCode,
    sizeClass,
    saveMode,
    openMode,
    supportsMiniSld,
    defaultTab,
  };
}

